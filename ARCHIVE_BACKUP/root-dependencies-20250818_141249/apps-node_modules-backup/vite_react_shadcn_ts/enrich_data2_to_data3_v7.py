class Data3Converter:
    """Converts data2 (CPML) to data3 format with exact structure compliance."""
    
    def __init__(self, config: Config):
        self.config = config
        self.music_theory = MusicTheoryEngine()
        self.spotify_client = SpotifyClient(config)
    
    def extract_chord_sequence(self, chords_str: str) -> List[str]:
        """Extract chord sequence from CPML format."""
        if not chords_str or not isinstance(chords_str, str):
            return []
        
        # Split by sections and extract chords
        sections = re.findall(r'(<[^>]+>|[\w#b°/]+)', chords_str)
        return [section.strip() for section in sections if section.strip()]
    
    def analyze_harmonic_profile(self, chord_sequence: List[str]) -> Dict[str, Any]:
        """Analyze harmonic profile and generate data3 columns."""
        if not chord_sequence:
            return {
                'key': 'unknown',
                'roman_numerals': '',
                'harmonic_fingerprint': '',
                'chord_counts': {chord: 0 for chord in self.config.chord_types}
            }
        
        # Detect key
        key, is_major, confidence = self.music_theory.detect_key(chord_sequence)
        
        # Generate Roman numerals
        roman_numerals = self.music_theory.assign_roman_numerals(chord_sequence, key, is_major)
        roman_str = ' '.join(roman_numerals)
        
        # Generate harmonic fingerprint
        harmonic_fingerprint = self.music_theory.generate_harmonic_fingerprint(chord_sequence, key)
        
        # Count chord types
        chord_counts = {chord: 0 for chord in self.config.chord_types}
        for roman in roman_numerals:
            if roman in chord_counts:
                chord_counts[roman] += 1
            else:
                chord_counts['Other'] += 1
        
        return {
            'key': key,
            'roman_numerals': roman_str,
            'harmonic_fingerprint': harmonic_fingerprint,
            'chord_counts': chord_counts
        }
    
    async def convert_data2_to_data3(self, input_file: str, output_file: str) -> Dict[str, Any]:
        """Convert data2 (CPML) to data3 format."""
        logger.info(f"Starting conversion from {input_file} to {output_file}")
        
        # Load data2
        df = pd.read_csv(input_file)
        total_songs = len(df)
        logger.info(f"Loaded {total_songs} songs from data2")
        
        # Enrich with Spotify metadata
        df = await self.spotify_client.batch_get_metadata(df)
        
        # Initialize data3 columns
        df['key'] = ''
        df['roman_numerals'] = ''
        df['harmonic_fingerprint'] = ''
        
        # Add chord type columns
        for chord_type in self.config.chord_types:
            df[chord_type] = 0
        
        # Process each song
        logger.info("Processing harmonic analysis...")
        for idx, row in df.iterrows():
            try:
                chords_str = row.get('chords', '')
                if not chords_str or pd.isna(chords_str):
                    continue
                
                # Extract chord sequence
                chord_sequence = self.extract_chord_sequence(chords_str)
                
                # Analyze harmonic profile
                analysis = self.analyze_harmonic_profile(chord_sequence)
                
                # Update DataFrame
                df.at[idx, 'key'] = analysis['key']
                df.at[idx, 'roman_numerals'] = analysis['roman_numerals']
                df.at[idx, 'harmonic_fingerprint'] = analysis['harmonic_fingerprint']
                
                # Update chord counts
                for chord_type, count in analysis['chord_counts'].items():
                    df.at[idx, chord_type] = count
                
                if idx % 1000 == 0:
                    logger.info(f"Processed {idx}/{total_songs} songs")
                    
            except Exception as e:
                logger.error(f"Error processing song {idx}: {e}")
                continue
        
        # Ensure exact data3 column order
        data3_columns = [
            'id', 'chords', 'release_date', 'genres', 'decade', 'rock_genre',
            'artist_id', 'main_genre', 'spotify_song_id', 'spotify_artist_id',
            'artist_name', 'artist_url', 'song_name', 'song_url',
            'key', 'roman_numerals', 'harmonic_fingerprint'
        ] + self.config.chord_types
        
        # Reorder columns to match data3 structure
        existing_columns = [col for col in data3_columns if col in df.columns]
        missing_columns = [col for col in data3_columns if col not in df.columns]
        
        # Add missing columns with default values
        for col in missing_columns:
            df[col] = ''
        
        # Reorder to exact data3 structure
        df = df[data3_columns]
        
        # Save data3
        df.to_csv(output_file, index=False)
        
        # Calculate metrics
        processed_songs = len(df[df['key'] != ''])
        success_rate = processed_songs / total_songs if total_songs > 0 else 0
        
        metrics = {
            'total_songs': total_songs,
            'processed_songs': processed_songs,
            'success_rate': success_rate,
            'output_file': output_file
        }
        
        logger.info(f"Conversion complete: {metrics}")
        return metrics

